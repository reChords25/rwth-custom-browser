// ==UserScript==
// @name         RWTH SSO Auto-Login (encrypted credentials)
// @namespace    http://tampermonkey.net/
// @version      2.0-2026-11
// @description  Automates RWTH SSO login using AES-GCM encrypted credentials and a device-local key
// @match        https://sso.rwth-aachen.de/idp/profile/SAML2/*
// @grant        GM_getValue
// @grant        GM_setValue
// @grant        GM_registerMenuCommand
// @run-at       document-idle
// ==/UserScript==

(async function () {
    'use strict';

    // ================= CONFIGURATION =================
    // Paste the encrypted string generated by the Tampermonkey menu command here:
    const ENCRYPTED_CREDS = ''

    // Step 2 (Dropdown): Optional partial text of the TOTP token you want selected.
    // Use Strg + Shift + C in Firefox to select the element that contains the name, e.g. "TOTP9235787B - TOTP - My Token"
    const TOTP_TOKEN_LABEL = 'TOTP9920567B - TOTP - VPN Script';

    // Prevent infinite loops if a login fails (cooldown in milliseconds)
    const COOLDOWN_MS = 15000;
    // =================================================

    const DEVICE_KEY_STORAGE = 'rwth_device_aes_key_v1';

    // --- Crypto Helpers (AES-GCM 256-bit) ---
    function bytesToBase64(bytes) {
        return btoa(String.fromCharCode(...bytes));
    }

    function base64ToBytes(b64) {
        return Uint8Array.from(atob(b64), c => c.charCodeAt(0));
    }

    async function getOrCreateDeviceKey() {
        let rawKeyB64 = GM_getValue(DEVICE_KEY_STORAGE, null);
        if (!rawKeyB64) {
            const rawKey = crypto.getRandomValues(new Uint8Array(32));
            rawKeyB64 = bytesToBase64(rawKey);
            GM_setValue(DEVICE_KEY_STORAGE, rawKeyB64);
        }
        return crypto.subtle.importKey(
            'raw',
            base64ToBytes(rawKeyB64),
            { name: 'AES-GCM' },
            false,
            ['encrypt', 'decrypt']
        );
    }

    async function encryptData(obj) {
        const key = await getOrCreateDeviceKey();
        const iv = crypto.getRandomValues(new Uint8Array(12));
        const encoded = new TextEncoder().encode(JSON.stringify(obj));
        const ciphertext = new Uint8Array(
            await crypto.subtle.encrypt({ name: 'AES-GCM', iv }, key, encoded)
        );
        const combined = new Uint8Array(iv.length + ciphertext.length);
        combined.set(iv, 0);
        combined.set(ciphertext, iv.length);
        return bytesToBase64(combined);
    }

    async function decryptData(b64) {
        const key = await getOrCreateDeviceKey();
        const combined = base64ToBytes(b64);
        const iv = combined.slice(0, 12);
        const ciphertext = combined.slice(12);
        const decrypted = await crypto.subtle.decrypt(
            { name: 'AES-GCM', iv },
            key,
            ciphertext
        );
        return JSON.parse(new TextDecoder().decode(decrypted));
    }

    // --- Menu Command to Generate Encrypted String ---
    GM_registerMenuCommand('Encrypt Credentials for This PC', async () => {
        const username = prompt('Enter RWTH Username (e.g. ab123456):');
        if (!username) return;
        const password = prompt('Enter RWTH Password:');
        if (!password) return;
        const totpSecret = prompt('Enter Base32 TOTP Secret:');
        if (!totpSecret) return;

        const encrypted = await encryptData({ username, password, totpSecret });
        prompt(
            'Copy this encrypted string and paste it into ENCRYPTED_CREDS in the script:',
            encrypted
        );
    });

    // Stop here if credentials haven't been pasted yet
    if (!ENCRYPTED_CREDS) {
        console.info('[RWTH Auto-Login] ENCRYPTED_CREDS is empty. Use the Tampermonkey menu to generate it.');
        return;
    }

    // Decrypt credentials using this device's local key
    let creds;
    try {
        creds = await decryptData(ENCRYPTED_CREDS);
    } catch (err) {
        console.error('[RWTH Auto-Login] Decryption failed. Wrong device key or corrupted ENCRYPTED_CREDS.', err);
        return;
    }

    // --- Helper Functions ---
    function isVisible(el) {
        return Boolean(el && !el.classList.contains('d-none') && el.offsetParent !== null);
    }

    const errorBanners = document.querySelectorAll('.alert-danger, .form-error, .output--error');
    for (const banner of errorBanners) {
        if (isVisible(banner)) {
            console.warn('[RWTH Auto-Login] Visible error detected. Aborting to prevent lockout.');
            return;
        }
    }

    function setFieldValue(element, value) {
        element.focus();
        element.value = value;
        element.dispatchEvent(new Event('input', { bubbles: true }));
        element.dispatchEvent(new Event('change', { bubbles: true }));
    }

    function isOnCooldown(stepKey) {
        const lastRun = Number(sessionStorage.getItem(stepKey) || 0);
        const now = Date.now();
        if (now - lastRun < COOLDOWN_MS) {
            console.warn(`[RWTH Auto-Login] Cooldown active for ${stepKey}. Aborting.`);
            return true;
        }
        sessionStorage.setItem(stepKey, String(now));
        return false;
    }

    function base32ToBytes(base32) {
        const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';
        const cleaned = base32.toUpperCase().replace(/[^A-Z2-7]/g, '');
        let bits = '';
        for (const char of cleaned) {
            bits += alphabet.indexOf(char).toString(2).padStart(5, '0');
        }
        const bytes = new Uint8Array(Math.floor(bits.length / 8));
        for (let i = 0; i < bytes.length; i++) {
            bytes[i] = parseInt(bits.slice(i * 8, i * 8 + 8), 2);
        }
        return bytes;
    }

    async function generateTOTP(secret) {
        const keyBytes = base32ToBytes(secret);
        let counter = Math.floor(Date.now() / 1000 / 30);
        const counterBytes = new Uint8Array(8);
        for (let i = 7; i >= 0; i--) {
            counterBytes[i] = counter & 0xff;
            counter = Math.floor(counter / 256);
        }

        const key = await crypto.subtle.importKey(
            'raw',
            keyBytes,
            { name: 'HMAC', hash: 'SHA-1' },
            false,
            ['sign']
        );

        const signature = new Uint8Array(await crypto.subtle.sign('HMAC', key, counterBytes));
        const offset = signature[signature.length - 1] & 0x0f;
        const binary =
            ((signature[offset] & 0x7f) << 24) |
            ((signature[offset + 1] & 0xff) << 16) |
            ((signature[offset + 2] & 0xff) << 8) |
            (signature[offset + 3] & 0xff);

        return (binary % 1000000).toString().padStart(6, '0');
    }

    const submitBtn = document.querySelector(
        '#login, button[name="_eventId_proceed"], input[name="_eventId_proceed"], button[type="submit"], input[type="submit"]'
    );
    if (!submitBtn) return;

    // ================= STEP 1: Username & Password =================
    const userInput = document.querySelector('#username');
    const passInput = document.querySelector('#password');

    if (userInput && passInput) {
        if (isOnCooldown('rwth_step1')) return;
        setFieldValue(userInput, creds.username);
        setFieldValue(passInput, creds.password);
        submitBtn.click();
        return;
    }

    // ================= STEP 2: TOTP Token Dropdown =================
    const tokenSelect = document.querySelector('form select');

    if (tokenSelect && isVisible(tokenSelect)) {
        if (isOnCooldown('rwth_step2')) return;

        if (TOTP_TOKEN_LABEL) {
            const match = Array.from(tokenSelect.options).find(opt =>
                opt.text.toLowerCase().includes(TOTP_TOKEN_LABEL.toLowerCase())
            );
            if (match) {
                tokenSelect.value = match.value;
                tokenSelect.dispatchEvent(new Event('change', { bubbles: true }));
            }
        }

        submitBtn.click();
        return;
    }

    // ================= STEP 4: TOTP Code Entry =================
    const totpInput = document.querySelector(
        'form input[type="text"], form input[type="tel"], form input[type="number"], form input[type="password"]'
    );

    if (totpInput && isVisible(totpInput)) {
        if (isOnCooldown('rwth_step4')) return;
        const code = await generateTOTP(creds.totpSecret);
        setFieldValue(totpInput, code);
        submitBtn.click();
    }
})();
